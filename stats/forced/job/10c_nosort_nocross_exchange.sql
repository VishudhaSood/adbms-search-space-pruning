LOAD 'pg_lab';
SET enable_indexscan = off; SET enable_indexonlyscan = off; SET enable_bitmapscan = off;
SET max_parallel_workers_per_gather = 0; SET geqo = off; SET jit = off;
/*=pg_lab= Config(plan_mode=full; exec_mode=sequential)
   JoinOrder((((ci chn) (((mc cn) t) ct)) rt))  HashJoin(ci chn)  HashJoin(mc cn)  HashJoin(mc cn t)  HashJoin(mc cn t ct)  HashJoin(ci chn mc cn t ct)  HashJoin(ci chn mc cn t ct rt)
   SeqScan(chn) SeqScan(ci) SeqScan(cn) SeqScan(ct) SeqScan(mc) SeqScan(rt) SeqScan(t) */
SELECT MIN(chn.name) AS character,
       MIN(t.title) AS movie_with_american_producer
FROM char_name AS chn,
     cast_info AS ci,
     company_name AS cn,
     company_type AS ct,
     movie_companies AS mc,
     role_type AS rt,
     title AS t
WHERE ci.note LIKE '%(producer)%'
  AND cn.country_code = '[us]'
  AND t.production_year > 1990
  AND t.id = mc.movie_id
  AND t.id = ci.movie_id
  AND ci.movie_id = mc.movie_id
  AND chn.id = ci.person_role_id
  AND rt.id = ci.role_id
  AND cn.id = mc.company_id
  AND ct.id = mc.company_type_id;
