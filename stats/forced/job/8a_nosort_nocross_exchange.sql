   JoinOrder((t (n1 (an1 ((ci rt) (mc cn))))))  HashJoin(ci rt)  HashJoin(mc cn)  HashJoin(ci rt mc cn)  HashJoin(an1 ci rt mc cn)  HashJoin(n1 an1 ci rt mc cn)  HashJoin(t n1 an1 ci rt mc cn)
