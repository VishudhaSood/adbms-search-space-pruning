LOAD 'pg_lab';
SET enable_indexscan = off; SET enable_indexonlyscan = off; SET enable_bitmapscan = off;
SET max_parallel_workers_per_gather = 0; SET geqo = off; SET jit = off;
/*=pg_lab= Config(plan_mode=full; exec_mode=sequential)
   JoinOrder((t ((((ci (mk k)) mc) cn) n)))  HashJoin(mk k)  HashJoin(ci mk k)  HashJoin(ci mk k mc)  HashJoin(ci mk k mc cn)  HashJoin(ci mk k mc cn n)  HashJoin(t ci mk k mc cn n)
   SeqScan(ci) SeqScan(cn) SeqScan(k) SeqScan(mc) SeqScan(mk) SeqScan(n) SeqScan(t) */
SELECT MIN(n.name) AS member_in_charnamed_movie
FROM cast_info AS ci,
     company_name AS cn,
     keyword AS k,
     movie_companies AS mc,
     movie_keyword AS mk,
     name AS n,
     title AS t
WHERE k.keyword ='character-name-in-title'
  AND n.name LIKE '%Bert%'
  AND n.id = ci.person_id
  AND ci.movie_id = t.id
  AND t.id = mk.movie_id
  AND mk.keyword_id = k.id
  AND t.id = mc.movie_id
  AND mc.company_id = cn.id
  AND ci.movie_id = mc.movie_id
  AND ci.movie_id = mk.movie_id
  AND mc.movie_id = mk.movie_id;
