#!/usr/bin/env python3
"""Day 3: build stats/search_space_counts.md from traces/pg_Q*.json and traces/calcite_Q*.json.

Run from the repo root:  python3 tools/make_counts.py
Re-run it whenever a trace changes; it overwrites the file.
"""
import json

rows = []
for i in range(1, 9):
    q = f"Q{i}"
    p = json.load(open(f"traces/pg_{q}.json"))["summary"]
    c = json.load(open(f"traces/calcite_{q}.json"))
    s = c["summary"]
    combos = len({tuple(x["tables"]) for x in c["sets"]})
    pruned = p["pruned_precheck"] + p["pruned_on_arrival"] + p["evicted_later"]
    rows.append((p["tables"], q, p, s, combos, pruned))
rows.sort(key=lambda r: (r[0], r[1]))

out = [
    "# Search-space counts: PostgreSQL vs Calcite (fair mode)",
    "",
    "Generated by `tools/make_counts.py` from `traces/`. PostgreSQL pruned = precheck + rejected on",
    "arrival + evicted later. Calcite prunes nothing: every RelNode stays in the memo.",
    "",
    "| Query | Tables | PG sets built | PG paths considered | PG pruned | PG pruned % | PG retained "
    "| Calcite table sets | Calcite RelSets | Calcite RelNodes | logical / physical "
    "| Calcite rule firings (attempted / produced) | Calcite winners | Calcite RelNodes per PG path |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
]
for n, q, p, s, combos, pruned in rows:
    pct = 100 * pruned / p["considered"] if p["considered"] else 0
    ratio = s["registered"] / p["considered"] if p["considered"] else 0
    out.append(
        f"| {q} | {n} | {p['sets_built']} | {p['considered']} | {pruned} | {pct:.0f}% | {p['retained']} "
        f"| {combos} | {s['relsets']} | {s['registered']} | {s['registered_logical']} / {s['registered_physical']} "
        f"| {s['rules_attempted']} / {s['rules_produced']} | {s['winners']} | {ratio:.1f}x |"
    )

out += [
    "",
    "## Detail: PostgreSQL pruning by kind",
    "",
    "| Query | Precheck (never built) | Rejected on arrival | Evicted later | Built | Retained |",
    "| --- | --- | --- | --- | --- | --- |",
]
for n, q, p, s, combos, pruned in rows:
    out.append(f"| {q} | {p['pruned_precheck']} | {p['pruned_on_arrival']} | {p['evicted_later']} "
               f"| {p['built']} | {p['retained']} |")

open("stats/search_space_counts.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
