#!/usr/bin/env python3
"""Task (iii), step 2: run Calcite's plan (forced with pg_lab hints) and PostgreSQL's own plan, and compare.

Reads stats/forced/index.json (made by tools/calcite_to_pglab.py). For every forceable plan whose vs_pg is not
"same", it opens one psql session per plan and runs:
  native = the query without hints (PostgreSQL's own plan)
  forced = the pg_lab hint block + the query (Calcite's plan)
Both use the index's preamble (LOAD 'pg_lab', fair mode, geqo off) + SET jit = off + a statement_timeout:
  1. EXPLAIN (FORMAT JSON)                                       -> PostgreSQL's estimated total cost
  2. 1 warm-up + RUNS x EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON)  -> median execution and planning time
pg_lab's check_final_path raises an error if the forced plan doesn't match the hints, so a forced run that
succeeds really is Calcite's plan.
Writes stats/forced/run_forced.md and run_forced.json; the last ANALYZE plan of every run goes to stats/forced/runs/.

Usage (repo root):
  python3 tools/run_forced.py            # small queries, DB test
  python3 tools/run_forced.py --job      # stats/forced/job/index.json, DB imdb
  python3 tools/run_forced.py --all      # also run plans whose vs_pg is "same"
  env: RUNS=5 TIMEOUT=5min DB=...
"""
import json, os, statistics, subprocess, sys

JOB = "--job" in sys.argv
ALL = "--all" in sys.argv
OUT = "stats/forced/job" if JOB else "stats/forced"
DB = os.environ.get("DB", "imdb" if JOB else "test")
RUNS = int(os.environ.get("RUNS", 5))
TIMEOUT = os.environ.get("TIMEOUT", "5min")
MARK = "@@@MARK@@@"

def run_plan(preamble, hint, sql):
    sql = sql.strip().rstrip(";")
    body = f"{hint}\n{sql}" if hint else sql
    lines = [preamble, "SET jit = off;", f"SET statement_timeout = '{TIMEOUT}';",
             f"\\echo {MARK}", f"EXPLAIN (FORMAT JSON) {body};"]
    for _ in range(RUNS + 1):                       # first ANALYZE run = warm-up
        lines += [f"\\echo {MARK}", f"EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) {body};"]
    p = subprocess.run(["psql", DB, "-X", "-q", "-A", "-t", "-P", "pager=off", "-f", "-"],
                       input="\n".join(lines) + "\n", capture_output=True, text=True)
    docs = []
    for part in p.stdout.split(MARK)[1:]:
        try:
            docs.append(json.loads(part.strip())[0])
        except (ValueError, IndexError):
            docs.append(None)
    err = p.stderr.strip()
    if not docs or docs[0] is None:
        raise SystemExit(f"EXPLAIN failed:\n{err[-1500:]}")
    cost = docs[0]["Plan"]["Total Cost"]
    runs = docs[2:]                                 # docs[1] is the warm-up
    if len(runs) < RUNS or any(r is None for r in runs):
        return {"cost": cost, "status": "timeout" if "timeout" in err else "error", "error": err[-500:]}
    ex = [r["Execution Time"] for r in runs]
    pl = [r["Planning Time"] for r in runs]
    return {"cost": cost, "status": "ok", "exec_ms": statistics.median(ex), "plan_ms": statistics.median(pl),
            "exec_runs": ex, "last": runs[-1]}

idx = json.load(open(f"{OUT}/index.json"))
todo = [e for e in idx if e.get("forceable") and (ALL or e.get("vs_pg") != "same")]
os.makedirs(f"{OUT}/runs", exist_ok=True)
results = []
for e in todo:
    name = os.path.basename(e["file"])[:-4]
    print(f"{name}: native ...", end=" ", flush=True)
    nat = run_plan(e["preamble"], "", e["sql"])
    print("forced ...", end=" ", flush=True)
    frc = run_plan(e["preamble"], e["hint"], e["sql"])
    for tag, r in (("native", nat), ("forced", frc)):
        if "last" in r:
            json.dump(r.pop("last"), open(f"{OUT}/runs/{name}_{tag}.json", "w"), indent=1)
    ok = nat["status"] == frc["status"] == "ok"
    row = {"plan": name, "query": e["query"], "modes": e["modes"], "vs_pg": e["vs_pg"],
           "calcite_cost": e.get("calcite_cost"), "native": nat, "forced": frc,
           "cost_ratio": frc["cost"] / nat["cost"],
           "runtime_ratio": frc["exec_ms"] / nat["exec_ms"] if ok else None}
    results.append(row)
    rr = f"x{row['runtime_ratio']:.2f}" if ok else frc["status"]
    print(f"cost {nat['cost']:.2f} -> {frc['cost']:.2f} (x{row['cost_ratio']:.3f}) | "
          f"exec {nat.get('exec_ms', 0):.3f} -> {frc.get('exec_ms', 0):.3f} ms ({rr})")

json.dump(results, open(f"{OUT}/run_forced.json", "w"), indent=1)

def ms(r):
    return f"{r['exec_ms']:.3f}" if r["status"] == "ok" else r["status"]

with open(f"{OUT}/run_forced.md", "w") as f:
    f.write("# Task (iii): Calcite's plan forced onto PostgreSQL vs PostgreSQL's own plan\n\n")
    f.write(f"Generated by `tools/run_forced.py`. DB `{DB}`; preamble from index.json (LOAD 'pg_lab', fair mode, "
            f"geqo off) + jit = off + statement_timeout {TIMEOUT}. Cost = EXPLAIN total cost (PostgreSQL's model). "
            f"Execution time = median of {RUNS} EXPLAIN ANALYZE runs after 1 warm-up.\n\n")
    f.write("| plan | Calcite modes | vs PG | Calcite cost | PG cost of Calcite's plan | PG cost of own plan "
            "| cost ratio | own plan exec (ms) | Calcite's plan exec (ms) | runtime ratio |\n")
    f.write("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
    for r in results:
        rr = f"{r['runtime_ratio']:.2f}" if r["runtime_ratio"] else "–"
        f.write(f"| {r['plan']} | {', '.join(r['modes'])} | {r['vs_pg']} | {r['calcite_cost']} | "
                f"{r['forced']['cost']:.2f} | {r['native']['cost']:.2f} | {r['cost_ratio']:.3f} | "
                f"{ms(r['native'])} | {ms(r['forced'])} | {rr} |\n")
print(f"wrote {OUT}/run_forced.md")
