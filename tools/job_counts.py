#!/usr/bin/env python3
"""Task (iv) on JOB: candidates generated vs retained, PostgreSQL vs Calcite (bottom-up and top-down).

Run from the repo root:
  python3 tools/job_counts.py                       # modes _nosort_nocross_exchange and _nosort_topdown_nocross_exchange
  python3 tools/job_counts.py _nosort_nocross_exchange _some_other_mode
Reads stats/pg_trace_job/summary.json (PG counts + untraced planning time), traces/job/pg_<q>.json[.gz] (sets built)
and traces/job/calcite_<q><mode>.json[.gz]. Writes stats/job_counts.md and stats/job_counts.json.

What is counted (the units differ, so compare growth and ratios, not raw numbers across engines):
  PostgreSQL  generated = paths considered (every path it computed a cost for, including those cut at precheck)
              retained  = paths still in a pathlist when set_cheapest ran, summed over all table sets
  Calcite     generated = RelNodes registered in the memo (logical + physical)
              retained  = bottom-up: every registered RelNode (the memo never drops one);
                          winners = cheapest node per RelSubset, the closest analogue to PG's retained paths
              top-down: generated is already smaller because branch-and-bound and the task order stop some
                          physical nodes from ever being created; "unimplemented" = RelSets with no physical node
"""
import glob, gzip, json, os, re, statistics, sys

MODES = sys.argv[1:] or ["_nosort_nocross_exchange", "_nosort_topdown_nocross_exchange"]


def load(path):
    for p in (path, path + ".gz"):
        if os.path.exists(p):
            with (gzip.open(p, "rt") if p.endswith(".gz") else open(p)) as f:
                return json.load(f)
    return None


def qkey(q):
    m = re.match(r"(\d+)([a-z]*)", q)
    return (int(m.group(1)), m.group(2)) if m else (10**6, q)


def calcite_counts(t):
    s = t["summary"]
    sets = t.get("sets") or []
    table_sets = len({tuple(sorted(x["tables"])) for x in sets}) if sets else None   # incl. single tables, like PG sets_built
    unimpl = None
    nodes = t.get("nodes")
    if nodes:
        phys = {n["set"] for n in nodes if n.get("physical")}
        unimpl = len({n["set"] for n in nodes if n.get("set") is not None} - phys)
    ms = s.get("planning_us_untraced_median") or (t.get("timing") or {}).get("planning_us_untraced_median")
    return {
        "generated": s["registered"], "logical": s["registered_logical"], "physical": s["registered_physical"],
        "relsets": s["relsets"], "winners": s["winners"], "table_sets": table_sets, "unimplemented": unimpl,
        "rules_produced": s.get("rules_produced"), "plan_ms": ms / 1000 if ms else None,
        "light": bool(t.get("light_trace")),
        "base_tables": len({x["tables"][0] for x in sets if len(x["tables"]) == 1}) or None,
    }


pg_sum = json.load(open("stats/pg_trace_job/summary.json"))
queries = set(pg_sum)
for m in MODES:
    for p in glob.glob(f"traces/job/calcite_*{m}.json*"):
        q = re.match(rf"traces/job/calcite_(.+?){re.escape(m)}\.json", p)
        if q:
            queries.add(q.group(1))

rows = []
for q in sorted(queries, key=qkey):
    r = {"query": q, "pg": None, "calcite": {}}
    if q in pg_sum:
        p = dict(pg_sum[q])
        tr = load(f"traces/job/pg_{q}.json")
        p["sets_built"] = tr["summary"]["sets_built"] if tr else None
        p["pruned"] = p["considered"] - p["retained"]
        r["pg"] = p
        r["tables"] = p["tables"]
    for m in MODES:
        t = load(f"traces/job/calcite_{q}{m}.json")
        if t:
            r["calcite"][m] = calcite_counts(t)
    if "tables" not in r:   # no PG trace: count base tables in any Calcite trace
        r["tables"] = next((c["base_tables"] for c in r["calcite"].values() if c.get("base_tables")), None)
    rows.append(r)


def fmt(x, d=0):
    if x is None:
        return "–"
    return f"{x:,.{d}f}" if isinstance(x, float) else f"{x:,}"


def rx(x, d=1):
    return "–" if x is None else f"{x:,.{d}f}x"


def med(xs):
    xs = [x for x in xs if x is not None]
    return statistics.median(xs) if xs else None


bu, td = (MODES + [None])[:2]
short = {bu: "BU", td: "TD"}
out = [
    "# Task (iv) on JOB: candidates generated vs retained",
    "",
    "Generated by `tools/job_counts.py`. PostgreSQL: fair mode on imdb_s10 (geqo off, index scans off), from",
    "`stats/pg_trace_job/summary.json` and `traces/job/pg_*.json`. Calcite: " +
    ", ".join(f"{short[m]} = `{m}`" for m in MODES if m) + ", from `traces/job/calcite_*.json[.gz]`.",
    "",
    "PG generated = paths costed (incl. precheck); PG retained = paths left when set_cheapest ran. Calcite generated =",
    "RelNodes registered; bottom-up retains all of them (nothing is ever removed from the memo); winners = cheapest node",
    "per RelSubset. The units differ: compare how each grows with the number of tables, and the ratios.",
    "",
    "## By number of tables (medians)",
    "",
    f"| Tables | Queries | PG generated | PG retained | PG pruned % | Calcite {short[bu]} generated (= retained) "
    f"| Calcite {short[bu]} winners | Calcite {short[bu]} / PG generated |"
    + (f" Calcite {short[td]} generated | {short[td]} / {short[bu]} |" if td else "")
    + f" PG planning ms | Calcite {short[bu]} planning ms |" + (f" Calcite {short[td]} planning ms |" if td else ""),
    "| " + " | ".join(["---"] * (13 if td else 10)) + " |",
]
by_n = {}
for r in rows:
    by_n.setdefault(r.get("tables"), []).append(r)
agg = []
for n in sorted(k for k in by_n if k is not None):
    rs = by_n[n]
    pg = [r["pg"] for r in rs if r["pg"]]
    b = [r["calcite"][bu] for r in rs if bu in r["calcite"]]
    t = [r["calcite"][td] for r in rs if td and td in r["calcite"]]
    ratio = med([r["calcite"][bu]["generated"] / r["pg"]["considered"]
                 for r in rs if r["pg"] and bu in r["calcite"] and r["pg"]["considered"]])
    td_bu = med([r["calcite"][td]["generated"] / r["calcite"][bu]["generated"]
                 for r in rs if td and td in r["calcite"] and bu in r["calcite"]])
    pct = med([100 * p["pruned"] / p["considered"] for p in pg if p["considered"]])
    a = {"tables": n, "queries": len(rs), "pg_generated": med([p["considered"] for p in pg]),
         "pg_retained": med([p["retained"] for p in pg]), "pg_pruned_pct": pct,
         "bu_generated": med([c["generated"] for c in b]), "bu_winners": med([c["winners"] for c in b]),
         "bu_over_pg": ratio, "td_generated": med([c["generated"] for c in t]), "td_over_bu": td_bu,
         "pg_ms": med([p.get("untraced_plan_ms") for p in pg]), "bu_ms": med([c["plan_ms"] for c in b]),
         "td_ms": med([c["plan_ms"] for c in t])}
    agg.append(a)
    line = (f"| {n} | {len(rs)} | {fmt(a['pg_generated'])} | {fmt(a['pg_retained'])} | {fmt(pct)}% "
            f"| {fmt(a['bu_generated'])} | {fmt(a['bu_winners'])} | {rx(ratio)} |")
    if td:
        line += f" {fmt(a['td_generated'])} | {rx(td_bu, 2)} |"
    line += f" {fmt(a['pg_ms'], 1)} | {fmt(a['bu_ms'], 1)} |" + (f" {fmt(a['td_ms'], 1)} |" if td else "")
    out.append(line)

out += [
    "",
    "## Per query",
    "",
    "| Query | Tables | PG sets built | PG generated | PG precheck | PG rejected | PG evicted | PG retained | PG pruned % "
    f"| Calcite table sets | {short[bu]} generated (log / phys) | {short[bu]} RelSets | {short[bu]} winners |"
    + (f" {short[td]} generated | {short[td]} unimplemented RelSets |" if td else "")
    + f" PG ms | {short[bu]} ms |" + (f" {short[td]} ms |" if td else ""),
    "| " + " | ".join(["---"] * (18 if td else 15)) + " |",
]
for r in rows:
    p = r["pg"] or {}
    b = r["calcite"].get(bu) or {}
    t = r["calcite"].get(td) or {} if td else {}
    pct = 100 * p["pruned"] / p["considered"] if p.get("considered") else None
    gen_b = (f"{fmt(b.get('generated'))} ({fmt(b.get('logical'))} / {fmt(b.get('physical'))})"
             + (" light" if b.get("light") else "")) if b else "–"
    line = (f"| {r['query']} | {fmt(r.get('tables'))} | {fmt(p.get('sets_built'))} | {fmt(p.get('considered'))} "
            f"| {fmt(p.get('precheck'))} | {fmt(p.get('rejected'))} | {fmt(p.get('evicted'))} | {fmt(p.get('retained'))} "
            f"| {fmt(pct)}{'%' if pct is not None else ''} | {fmt(b.get('table_sets'))} | {gen_b} | {fmt(b.get('relsets'))} "
            f"| {fmt(b.get('winners'))} |")
    if td:
        line += f" {fmt(t.get('generated'))} | {fmt(t.get('unimplemented'))} |"
    line += f" {fmt(p.get('untraced_plan_ms'), 1)} | {fmt(b.get('plan_ms'), 1)} |" + (f" {fmt(t.get('plan_ms'), 1)} |" if td else "")
    out.append(line)

out += [
    "",
    "Notes: `light` = Calcite trace above the detail limit (counts kept, per-node detail dropped), so unimplemented",
    "RelSets can't be counted. A dash means that trace doesn't exist (PG: the 9 queries with more than 12 tables;",
    "top-down: families 29-33 not reached).",
]

os.makedirs("stats", exist_ok=True)
open("stats/job_counts.md", "w").write("\n".join(out) + "\n")
json.dump({"modes": MODES, "by_tables": agg, "queries": rows}, open("stats/job_counts.json", "w"), indent=1)
print("\n".join(out[:12 + len(agg)]))
print(f"\n{len(rows)} queries; wrote stats/job_counts.md and stats/job_counts.json")
