#!/usr/bin/env python3
"""Planning-time overhead of the trace patch.
For each query in tools/queries.txt, one psql session per mode:
1 warm-up + RUNS x EXPLAIN (SUMMARY); the median Planning Time is reported.
  untraced: client_min_messages = notice (TRACE lines are skipped)
  traced:   client_min_messages = log    (TRACE lines are sent to psql, as in pg_trace.sh)
Both use log_min_messages = fatal, so nothing goes to the server log.
Usage (from /workspaces/pg_dev):  python3 tools/pg_overhead.py   [env: RUNS=5 DB=test ONLY=Q4]
Writes stats/pg_planning_overhead.md"""
import os, re, statistics, subprocess

RUNS = int(os.environ.get("RUNS", 5))
DB = os.environ.get("DB", "test")
SETS = ("SET max_parallel_workers_per_gather = 0; SET jit = off; "
        "SET enable_indexscan = off; SET enable_bitmapscan = off; SET enable_indexonlyscan = off; "
        "SET log_min_messages = fatal; ")

def planning_times(sql, client_level):
    script = SETS + f"SET client_min_messages = {client_level};\n" + \
             "\n".join([f"EXPLAIN (SUMMARY) {sql};"] * (RUNS + 1)) + "\n"
    out = subprocess.run(["psql", DB, "-X", "-q", "-v", "ON_ERROR_STOP=1", "-P", "pager=off", "-f", "-"],
                         input=script, capture_output=True, text=True, check=True).stdout
    t = [float(x) for x in re.findall(r"Planning Time: ([\d.]+) ms", out)]
    if len(t) != RUNS + 1:
        raise SystemExit(f"expected {RUNS + 1} planning times, got {len(t)}:\n{out[-800:]}")
    return t[1:]                      # drop the warm-up run

rows = []
for line in open("tools/queries.txt"):
    if "|" not in line:
        continue
    q, sql = line.rstrip("\n").split("|", 1)
    if os.environ.get("ONLY") and q != os.environ["ONLY"]:
        continue
    u = planning_times(sql, "notice")
    tr = planning_times(sql, "log")
    mu, mt = statistics.median(u), statistics.median(tr)
    rows.append((q, mu, mt, u, tr))
    print(f"{q}: untraced {mu:.3f} ms | traced {mt:.3f} ms | traced/untraced x{mt / mu:.1f}", flush=True)

with open("stats/pg_planning_overhead.md", "w") as f:
    f.write("# PostgreSQL planning time: traced vs untraced\n\n")
    f.write(f"Generated by `tools/pg_overhead.py`. DB `{DB}`, fair mode, log_min_messages = fatal, "
            f"1 warm-up + {RUNS} runs per mode in one session, median of EXPLAIN (SUMMARY) Planning Time.\n\n")
    f.write("| query | untraced median (ms) | traced median (ms) | traced / untraced | replay scale = untraced / traced | untraced runs | traced runs |\n")
    f.write("| --- | --- | --- | --- | --- | --- | --- |\n")
    for q, mu, mt, u, tr in rows:
        f.write(f"| {q} | {mu:.3f} | {mt:.3f} | {mt / mu:.1f} | {mu / mt:.3f} | "
                f"{', '.join(f'{x:.3f}' for x in u)} | {', '.join(f'{x:.3f}' for x in tr)} |\n")
print("wrote stats/pg_planning_overhead.md")
